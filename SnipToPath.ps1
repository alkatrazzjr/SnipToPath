public static bool TryReplaceIfCurrent(System.IntPtr ownerHwnd, uint expectedSequence, string text) {
    if (text == null) { throw new System.ArgumentNullException("text"); }
    if (ownerHwnd == System.IntPtr.Zero) { throw new System.ArgumentException("Clipboard owner window is required", "ownerHwnd"); }
    if (!OpenClipboard(ownerHwnd)) { return false; }
    try {
        if (GetClipboardSequenceNumber() != expectedSequence) { return false; }
        byte[] bytes = System.Text.Encoding.Unicode.GetBytes(text + "\0");
        System.IntPtr allocation = GlobalAlloc(0x0002, new System.UIntPtr((uint)bytes.Length));
        if (allocation == System.IntPtr.Zero) { return false; }
        try {
            System.IntPtr pointer = GlobalLock(allocation);
            if (pointer == System.IntPtr.Zero) { return false; }
            try { System.Runtime.InteropServices.Marshal.Copy(bytes, 0, pointer, bytes.Length); }
            finally { GlobalUnlock(allocation); }
            if (!EmptyClipboard()) { return false; }
            if (SetClipboardData(13, allocation) == System.IntPtr.Zero) { return false; }
            allocation = System.IntPtr.Zero; // clipboard owns the HGLOBAL now
            return true;
        }
        finally {
            if (allocation != System.IntPtr.Zero) { GlobalFree(allocation); }
        }
    }
    finally { CloseClipboard(); }
}
