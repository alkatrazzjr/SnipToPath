# Unit tests run on a Windows GitHub Actions runner (PowerShell 5.1).
$ErrorActionPreference = 'Stop'
$source = Get-Content (Join-Path $PSScriptRoot '..\SnipToPath.ps1') -Raw -Encoding UTF8
$tokens = $null; $errors = $null
$ast = [System.Management.Automation.Language.Parser]::ParseInput($source, [ref]$tokens, [ref]$errors)
if ($errors.Count) { throw 'Application source has parse errors' }

foreach ($name in @('Remove-OwnScreenshots', 'Queue-PreviousScreenshot', 'Invoke-PendingScreenshotCleanup', 'Install-ScriptSafely')) {
    $defs = @($ast.FindAll({ param($node)
        $node -is [System.Management.Automation.Language.FunctionDefinitionAst] -and $node.Name -eq $name
    }, $true))
    if ($defs.Count -ne 1) { throw "Missing or duplicated function: $name" }
    Invoke-Expression $defs[0].Extent.Text
}
function Write-Log([string]$message) { Write-Warning $message }

# Only delete files with names in the exact format generated by SnipToPath.
$folder = Join-Path ([IO.Path]::GetTempPath()) ('sniptopath-tests-' + [guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Path $folder -Force | Out-Null
$owned = Join-Path $folder 'snip-20261014-042209-227-a1b2c3.png'
$foreign = Join-Path $folder 'snip-important.png'
$foreign2 = Join-Path $folder 'snip-20261014-042209-227-NOTMYFILE.png'
try {
    foreach ($file in @($owned, $foreign, $foreign2)) { [IO.File]::WriteAllBytes($file, [byte[]](1,2,3,4)) }
    $deleted = Remove-OwnScreenshots $folder
    if ($deleted -ne 1 -or (Test-Path $owned) -or -not (Test-Path $foreign) -or -not (Test-Path $foreign2)) {
        throw 'Cleanup deleted an unrelated file or failed to delete its own file'
    }
    Write-Host 'PASS strict screenshot cleanup (no unrelated files deleted)'

    $script:config = @{ AutoDeleteOnCopy = $true; DeleteDelayMinutes = 15 }
    $script:pendingScreenshotDeletes = New-Object 'System.Collections.Generic.List[object]'
    $path = Join-Path $folder 'snip-20261014-043000-015-abcdef.png'
    [IO.File]::WriteAllBytes($path, [byte[]](5,6,7))
    $script:lastScreenshotPath = $path
    Queue-PreviousScreenshot
    if ($script:pendingScreenshotDeletes.Count -ne 1) { throw 'Missing scheduled cleanup' }
    $delay = ($script:pendingScreenshotDeletes[0].DeleteAfter - [DateTime]::UtcNow).TotalMinutes
    if ($delay -lt 14 -or $delay -gt 16) { throw 'Wrong cleanup delay' }
    Invoke-PendingScreenshotCleanup
    if (-not (Test-Path $path)) { throw 'Screenshot deleted too early' }
    $script:pendingScreenshotDeletes[0].DeleteAfter = [DateTime]::UtcNow.AddSeconds(-1)
    Invoke-PendingScreenshotCleanup
    if (Test-Path $path) { throw 'Expired screenshot was not deleted' }
    Write-Host 'PASS delayed screenshot cleanup'
}
finally { Remove-Item -LiteralPath $folder -Recurse -Force -ErrorAction SilentlyContinue }

# Compile the exact native implementation shipped with the app.
$pattern = "(?s)Add-Type -Namespace SnipNative -Name ClipboardCounter -MemberDefinition @'\r?\n(.*?)\r?\n'@"
$match = [regex]::Match($source, $pattern)
if (-not $match.Success) { throw 'Native clipboard implementation missing' }
Add-Type -Namespace SnipNative -Name ClipboardCounter -MemberDefinition $match.Groups[1].Value
$nativeMethod = [SnipNative.ClipboardCounter].GetMethod('TryReplaceIfCurrent')
if (-not $nativeMethod -or $nativeMethod.GetParameters().Count -ne 3) { throw 'Missing guarded clipboard method' }
Write-Host 'PASS native clipboard implementation compiles'

# GitHub hosted Windows runners may not have an interactive clipboard, so don't
# claim a behavioral pass if none is available. Real clipboard tests run when it is.
Add-Type -AssemblyName System.Windows.Forms
$owner = New-Object System.Windows.Forms.Form
try {
    $hWnd = $owner.Handle
    $sequence = [SnipNative.ClipboardCounter]::GetClipboardSequenceNumber()
    $text = 'SnipToPath-clipboard-test-' + [guid]::NewGuid().ToString('N')
    try {
        [Windows.Forms.Clipboard]::SetText($text)
        if ([Windows.Forms.Clipboard]::GetText() -ne $text) { throw 'Clipboard text test setup failed' }
        $sequence2 = [SnipNative.ClipboardCounter]::GetClipboardSequenceNumber()
        if ($sequence2 -eq $sequence) { throw 'Clipboard sequence did not change' }
        $shouldBeFalse = [SnipNative.ClipboardCounter]::TryReplaceIfCurrent($hWnd, [uint32]$sequence, 'SHOULD_NOT_APPEAR')
        if ($shouldBeFalse -or [Windows.Forms.Clipboard]::GetText() -ne $text) {
            throw 'Stale clipboard write overwrote newer content'
        }
        if (-not [SnipNative.ClipboardCounter]::TryReplaceIfCurrent($hWnd, [uint32]$sequence2, 'SnipToPath-guarded-write')) {
            throw 'Current clipboard write unexpectedly failed'
        }
        if ([Windows.Forms.Clipboard]::GetText() -ne 'SnipToPath-guarded-write') { throw 'Clipboard text contents incorrect' }
        Write-Host 'PASS guarded clipboard read/write with stale-sequence protection'
    }
    finally {
        # Clear our marker from runner's clipboard without touching user files.
        try { [Windows.Forms.Clipboard]::Clear() } catch {}
    }
}
finally { $owner.Dispose() }

# Exercise the actual updater helper on Windows, not a copy of the Replace call.
# This catches .NET Framework's ArgumentException when backupFileName is $null.
$installRoot = Join-Path ([IO.Path]::GetTempPath()) ('SnipToPath installation test ' + [Guid]::NewGuid().ToString('N'))
$sourcePath = Join-Path $installRoot 'downloaded.ps1'
$installedPath = Join-Path $installRoot 'installed\SnipToPath.ps1'
try {
    [void][IO.Directory]::CreateDirectory($installRoot)
    [IO.File]::WriteAllText($sourcePath, 'first version', [Text.Encoding]::UTF8)

    # Fresh installation must work when no destination file exists.
    Install-ScriptSafely $sourcePath $installedPath
    if ([IO.File]::ReadAllText($installedPath) -ne 'first version') {
        throw 'Fresh install did not write the downloaded script'
    }
    Write-Host 'PASS fresh installation into an empty folder'

    # An existing installation must be atomically replaced without an invalid backup path.
    [IO.File]::WriteAllText($sourcePath, 'updated version', [Text.Encoding]::UTF8)
    Install-ScriptSafely $sourcePath $installedPath
    if ([IO.File]::ReadAllText($installedPath) -ne 'updated version') {
        throw 'Update did not replace existing installed script'
    }
    $leftovers = @(Get-ChildItem (Split-Path -Parent $installedPath) -File |
        Where-Object { $_.Name -match '^SnipToPath-[a-f0-9]{32}\.(tmp|bak)$' })
    if ($leftovers.Count) { throw 'Installation left temporary or backup files behind' }
    Write-Host 'PASS updating an existing installation with a real backup path'

    # Re-running from its own installed path should do nothing.
    Install-ScriptSafely $installedPath $installedPath
    if ([IO.File]::ReadAllText($installedPath) -ne 'updated version') {
        throw 'Self-update unexpectedly modified the installed script'
    }
    Write-Host 'PASS installing from the installed script path'

    # A missing downloaded file must not damage the previously working version.
    try {
        Install-ScriptSafely (Join-Path $installRoot 'missing.ps1') $installedPath
        throw 'Expected missing source to fail'
    }
    catch [System.IO.FileNotFoundException] {
        if ([IO.File]::ReadAllText($installedPath) -ne 'updated version') {
            throw 'Failed update corrupted previous installation'
        }
    }
    Write-Host 'PASS failed update preserves the installed version'
}
finally {
    if (Test-Path -LiteralPath $installRoot) {
        Remove-Item -LiteralPath $installRoot -Force -Recurse
    }
}
